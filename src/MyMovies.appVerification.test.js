import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import App from './App';
import axios from 'axios';
import { reelbotCloudService } from './services/reelbotCloudService';
import { tasteProfileService } from './services/tasteProfileService';
let mockAuthListener;
let mockGetSession = jest.fn();
jest.mock('axios');
jest.mock('./lib/supabaseClient', () => ({isSupabaseConfigured:true, getSupabaseClient:async()=>({auth:{getSession:()=>mockGetSession(), onAuthStateChange: callback => {mockAuthListener=callback; return {data:{subscription:{unsubscribe:jest.fn()}}};}}})}));
jest.mock('./services/reelbotCloudService', () => ({reelbotCloudService:{isConfigured:true,getLocalProfileOwner:jest.fn(()=>''),clearLocalAccountCache:jest.fn(),bootstrapUserState:jest.fn(),saveUserState:jest.fn(),activateLocalCache:jest.fn()}}));
const movie={id:23168,title:'The Town',release_date:'2010-09-15'};
const snapshot=profile=>({profile,interactions:[],homePickSession:null});
const session=id=>({user:{id,email:`${id}@example.test`,user_metadata:{}}});
const deferred=()=>{let resolve,reject; const promise=new Promise((yes,no)=>{resolve=yes;reject=no});return{promise,resolve,reject}};
beforeEach(()=>{localStorage.clear();jest.clearAllMocks();window.scrollTo=jest.fn();Element.prototype.scrollIntoView=jest.fn();axios.get.mockResolvedValue({data:{results:[],total_pages:1,total_results:0}});window.history.replaceState({},'','/my-movies');mockGetSession.mockResolvedValue({data:{session:session('owner-a')}});reelbotCloudService.bootstrapUserState.mockResolvedValue(snapshot(tasteProfileService.toggleWatchlist(tasteProfileService.createEmptyProfile(),movie)));reelbotCloudService.saveUserState.mockImplementation(async(id,p)=>snapshot(p));});
test('real App auth restoration and real Ask registration hide library until ready; route return and account switch work',async()=>{
 const auth=deferred(), cloud=deferred();mockGetSession.mockReturnValueOnce(auth.promise);reelbotCloudService.bootstrapUserState.mockReturnValueOnce(cloud.promise);
 render(<App/>);
 await screen.findByText('Loading your movies…');
 expect(screen.queryByText('Sign in to see your movies')).not.toBeInTheDocument();
 await act(async()=>auth.resolve({data:{session:session('owner-a')}}));
 expect(screen.queryByRole('group',{name:'Saved movie lists'})).not.toBeInTheDocument();
 await act(async()=>cloud.resolve(snapshot(tasteProfileService.toggleWatchlist(tasteProfileService.createEmptyProfile(),movie))));
 await screen.findByRole('heading',{name:movie.title});
 fireEvent.click(within(screen.getByRole('navigation',{name:'Primary'})).getByRole('link',{name:'Browse'}));
 await waitFor(()=>expect(window.location.pathname).toBe('/browse'));
 fireEvent.click(within(screen.getByRole('navigation',{name:'Primary'})).getByRole('link',{name:'My Movies'}));
 await screen.findByRole('heading',{name:movie.title});
 const next=deferred();reelbotCloudService.bootstrapUserState.mockReturnValueOnce(next.promise);
 act(()=>mockAuthListener('SIGNED_IN',session('owner-b')));
 expect(screen.queryByRole('heading',{name:movie.title})).not.toBeInTheDocument();
 expect(screen.getByText('Loading your movies…')).toBeInTheDocument();
 await act(async()=>next.resolve(snapshot(tasteProfileService.createEmptyProfile())));
 await screen.findByText('No saved movies yet.');
 act(()=>mockAuthListener('SIGNED_OUT',null));
 await screen.findByText('Sign in to see your movies');
 expect(screen.queryByRole('group',{name:'Saved movie lists'})).not.toBeInTheDocument();
});
test('real App renders restoration failure then fresh mount recovery',async()=>{
 reelbotCloudService.bootstrapUserState.mockRejectedValueOnce(Error('Connection interrupted.'));
 const view=render(<App/>);
 await screen.findByText('Your movies couldn’t be loaded.');
 expect(screen.queryByText('No saved movies yet.')).not.toBeInTheDocument();
 view.unmount();render(<App/>);
 await screen.findByRole('heading',{name:movie.title});
});
